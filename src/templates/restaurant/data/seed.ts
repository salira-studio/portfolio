function makeItem(
  id: string,
  menuItemId: string,
  name: string,
  price: number,
  qty: number,
  opts: { groupId: string; optionId: string }[] = [],
) {
  return {
    id,
    menuItemId,
    name,
    price,
    quantity: qty,
    selectedOptions: opts,
    subtotal: price * qty,
  }
}

